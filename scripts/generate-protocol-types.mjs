#!/usr/bin/env node
// Generates src/shared/protocol/generated/backendProtocolSchema.ts from the single protocol
// definition in python-backend/protocol_schema.py. `--write` regenerates; without it the
// script only checks that the committed file is current (used by verify).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src/shared/protocol/generated/backendProtocolSchema.ts');
const python = [join(root, '.venv/bin/python'), join(root, '.venv/Scripts/python.exe')].find(existsSync) ?? 'python3';
const dumped = spawnSync(python, ['protocol_schema.py'], { cwd: join(root, 'python-backend'), encoding: 'utf8' });
if (dumped.status !== 0) throw new Error(`python protocol_schema.py failed:\n${dumped.stderr}`);
const schema = JSON.parse(dumped.stdout);
const definitions = schema.$defs;
const externalTypes = new Set();

function typeOf(node) {
    if (node.$ref) {
        const name = node.$ref.replace('#/$defs/', '');
        const definition = definitions[name];
        if (definition['x-tsType']) { externalTypes.add(definition['x-tsType']); return definition['x-tsType']; }
        return definition.type === 'object' ? name : typeOf(definition);
    }
    if (node.const !== undefined) return JSON.stringify(node.const);
    if (node.enum) return node.enum.map(value => JSON.stringify(value)).join(' | ');
    switch (node.type) {
        case 'string': return 'string';
        case 'number': case 'integer': return 'number';
        case 'boolean': return 'boolean';
        case 'array': return `${wrap(typeOf(node.items))}[]`;
        case 'object': return node.properties ? objectBody(node, '') : 'Record<string, unknown>';
        default: throw new Error(`protocol_schema.py: unsupported schema node ${JSON.stringify(node)}`);
    }
}
const wrap = type => (/[ |]/.test(type) && !type.startsWith('{') ? `(${type})` : type);
function objectBody(node, indent) {
    const required = new Set(node.required ?? []);
    const lines = Object.entries(node.properties).map(([key, child]) =>
        `${indent}    ${/^[A-Za-z_]\w*$/.test(key) ? key : JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${typeOf(child)};`);
    return `{\n${lines.join('\n')}\n${indent}}`;
}

const interfaces = Object.entries(definitions)
    .filter(([, definition]) => definition.type === 'object' && definition.properties && !definition['x-tsType'])
    .map(([name, definition]) => `export interface ${name} ${objectBody(definition, '')}`);
const commands = Object.keys(schema['x-commands']);
const output = [
    '// Generated by scripts/generate-protocol-types.mjs from python-backend/protocol_schema.py.',
    '// Do not edit; change the Python schema and run `node scripts/generate-protocol-types.mjs --write`.',
    externalTypes.size ? `import type { ${[...externalTypes].sort().join(', ')} } from '../../analysis/analysisTypes';\n` : '',
    `export const BACKEND_PROTOCOL_SCHEMA = ${JSON.stringify(schema, null, 4)} as const;`,
    '',
    `export type SchemaCommand = ${commands.map(command => `'${command}'`).join(' | ')};`,
    '',
    interfaces.join('\n\n'),
    '',
].join('\n');

const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
if (current === output) {
    console.log('Generated protocol types match python-backend/protocol_schema.py');
} else if (process.argv.includes('--write')) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, output);
    console.log(`Wrote ${target}`);
} else {
    console.error('✗ src/shared/protocol/generated/backendProtocolSchema.ts is out of date; run node scripts/generate-protocol-types.mjs --write');
    process.exit(1);
}
