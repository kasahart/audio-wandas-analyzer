// Copies python-backend/batch/run_recipe.py into src/shared/batch/runRecipeScript.ts, which the webview writes
// into a recipe bundle. The Python file is the source (ruff-checked, run end to end by pytest); a node test
// fails when the copy is behind it: run `node scripts/generate-run-recipe-script.mjs` after editing it.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const script = readFileSync(path.join(root, 'python-backend', 'batch', 'run_recipe.py'), 'utf8');
writeFileSync(path.join(root, 'src', 'shared', 'batch', 'runRecipeScript.ts'),
    `// Generated by scripts/generate-run-recipe-script.mjs from python-backend/batch/run_recipe.py: edit that file.\nexport const RUN_RECIPE_PY = ${JSON.stringify(script)};\n`);
