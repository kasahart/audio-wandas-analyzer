"""The Compare step bar's preset recipes: chains to start from, chosen by what the user wants to look at.

Each preset is an ordinary wandas Recipe (``RecipePlan.to_dict()``) built here by running the chain on a
stand-in frame, the way ``recipe_builder`` saves the entry Recipe, so the step bar loads the same JSON
wandas would replay. Every preset slices the region (``trim``) before it turns the signal into anything
else, so the comparison's region applies to the sound itself. The first preset is the entry Recipe.

``python recipe_presets.py --write`` writes src/shared/recipe/generated/recipePresets.ts, which
test_recipe_presets.py keeps equal to this module. Names and descriptions are the Webview's strings.
"""

from __future__ import annotations

import json
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

import wandas as wd
from wandas.pipeline import RecipePlan

from recipe_builder import ENTRY_HPF_HZ, RecipeSource, _stand_in, entry_scan_recipe

TS_TARGET = Path(__file__).parents[1] / "src" / "shared" / "recipe" / "generated" / "recipePresets.ts"

#: 1/3-octave bands of the band-level preset, as a new noct_spectrum step starts (recipeSteps.ts).
OCTAVE_FMIN_HZ = 25.0
OCTAVE_FMAX_HZ = 6300.0

_SOURCE = RecipeSource(1, 16000.0)


def _region(*, highpass: bool = True) -> wd.ChannelFrame:
    """The stand-in, high-passed like the entry Recipe, then sliced to the region (the whole file until one is set)."""
    signal = _stand_in(_SOURCE, 4096)
    if highpass:
        signal = signal.high_pass_filter(cutoff=ENTRY_HPF_HZ)
    return signal.trim(start=0.0, end=None)


def _plan(frame: Any) -> dict[str, Any]:
    return RecipePlan.from_frame(frame, input_names=("signal",)).to_dict()


#: id → builder, in the order the menu lists them (from a first look at everything to particular measures).
PRESETS: dict[str, Callable[[], dict[str, Any]]] = {
    "spectrum": entry_scan_recipe,
    "octave": lambda: _plan(_region().a_weighting().noct_spectrum(fmin=OCTAVE_FMIN_HZ, fmax=OCTAVE_FMAX_HZ, n=3)),
    "spectrogram": lambda: _plan(_region().stft()),
    "level": lambda: _plan(_region().a_weighting().rms_trend(dB=True)),
    "loudness": lambda: _plan(_region(highpass=False).loudness_zwtv()),
    "roughness": lambda: _plan(_region(highpass=False).roughness_dw()),
}


def presets() -> list[dict[str, Any]]:
    return [{"id": preset_id, "recipe": build()} for preset_id, build in PRESETS.items()]


def typescript(items: list[dict[str, Any]]) -> str:
    body = json.dumps(items, indent=4, ensure_ascii=False)
    return (
        "// Generated by python-backend/recipe_presets.py from wandas RecipePlans.\n"
        "// Do not edit; run `python python-backend/recipe_presets.py --write`.\n"
        "import type { RecipeDocument } from '../recipeSelection';\n\n"
        "export interface RecipePreset {\n"
        "    id: string;\n"
        "    recipe: RecipeDocument;\n"
        "}\n\n"
        f"export const RECIPE_PRESETS: readonly RecipePreset[] = {body} as unknown as readonly RecipePreset[];\n"
    )


if __name__ == "__main__":
    text = typescript(presets())
    if "--write" in sys.argv:
        TS_TARGET.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
